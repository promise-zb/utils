import { describe, expect, it } from 'vitest'
import { calcAreas, formatResult } from './calc'
import { areaStatus, type TextBox } from './types'

function at(text: string, cx: number, cy: number, w = 56, h = 18): TextBox {
  return { text, x: cx - w / 2, y: cy - h / 2, w, h }
}

describe('calcAreas', () => {
  it('没有长度时不计算', () => {
    const result = calcAreas([at('卧室', 100, 80), at('客厅', 220, 80)])
    expect(result.status).toBe(areaStatus.noLength)
    expect(formatResult(result)).toBe('没有长度，无需计算')
  })

  it('只有外框尺寸时给出总面积，房间不计算', () => {
    const result = calcAreas([
      at('13140', 500, 24, 70, 18),
      at('12240', 980, 420, 70, 18),
      at('卧室', 180, 160),
      at('客厅', 640, 460),
    ])
    expect(formatResult(result)).toBe(['总面积：160.83 m²', '未计算：卧室、客厅'].join('\n'))
  })

  it('左右尺寸不一致时只计算能闭合的房间', () => {
    const result = calcAreas([
      at('12200', 520, 24, 70, 18),
      at('3900', 196, 80, 52, 18),
      at('3600', 496, 80, 52, 18),
      at('600', 664, 80, 40, 18),
      at('3900', 844, 80, 52, 18),
      at('11220', 24, 450, 60, 18),
      at('3300', 70, 235.5, 52, 18),
      at('2400', 70, 435, 52, 18),
      at('4800', 70, 687, 52, 18),
      at('11220', 1040, 450, 60, 18),
      at('3300', 980, 235.5, 52, 18),
      at('1800', 980, 414, 52, 18),
      at('4800', 980, 645, 52, 18),
      at('3900', 196, 760, 52, 18),
      at('3600', 496, 760, 52, 18),
      at('4500', 760, 760, 52, 18),
      at('卧室', 196, 235),
      at('餐厅', 496, 235),
      at('厨房', 844, 235),
      at('储物间', 196, 435, 72, 18),
      at('卫生间', 844, 414),
      at('客厅', 844, 645),
      at('卧室', 196, 687),
      at('堂屋', 496, 600),
    ])
    expect(formatResult(result)).toBe(
      [
        '总面积：93.42 m²',
        '卧室1：12.87 m²',
        '餐厅：11.88 m²',
        'A：1.98 m²',
        '厨房：12.87 m²',
        '储物间：9.36 m²',
        '卫生间：7.02 m²',
        '客厅：18.72 m²',
        '卧室2：18.72 m²',
        '未计算：堂屋',
      ].join('\n'),
    )
  })

  it('图纸上的面积标注优先，拆开的文字会合并', () => {
    const result = calcAreas([
      at('单', 80, 70, 18, 18),
      at('间', 100, 70, 18, 18),
      at('15.2', 90, 100, 36, 16),
      at('㎡', 122, 100, 20, 16),
      at('房', 230, 70, 18, 18),
      at('间', 250, 70, 18, 18),
      at('12.1㎡', 240, 100, 64, 16),
      at('房间', 240, 180),
      at('13.9㎡', 240, 210, 64, 16),
      at('12200', 160, 16, 70, 16),
      at('8000', 16, 160, 48, 16),
    ])
    expect(result.status).toBe(areaStatus.ok)
    expect(formatResult(result)).toBe(
      ['总面积：41.20 m²', '单间：15.20 m²', '房间1：12.10 m²', '房间2：13.90 m²'].join('\n'),
    )
  })

  it('只有左侧竖向尺寸时只计算最左列', () => {
    const result = calcAreas([
      at('3900', 196, 80, 52, 18),
      at('3600', 496, 80, 52, 18),
      at('600', 664, 80, 40, 18),
      at('3900', 844, 80, 52, 18),
      at('3300', 70, 235.5, 52, 18),
      at('2400', 70, 435, 52, 18),
      at('4800', 70, 687, 52, 18),
      at('3900', 196, 760, 52, 18),
      at('3600', 496, 760, 52, 18),
      at('4500', 760, 760, 52, 18),
      at('卧室', 196, 235),
      at('餐厅', 496, 235),
      at('储物间', 196, 435, 72, 18),
      at('卧室', 196, 687),
      at('厨房', 844, 235),
    ])
    expect(formatResult(result)).toBe(
      [
        '总面积：40.95 m²',
        '卧室1：12.87 m²',
        '储物间：9.36 m²',
        '卧室2：18.72 m²',
        '未计算：餐厅、厨房',
      ].join('\n'),
    )
  })

  it('识别差几毫米时收成附近的尺寸', () => {
    const result = calcAreas([
      at('13140', 500, 24, 70, 18),
      at('609', 980, 420, 40, 18),
      at('卧室', 180, 160),
      at('客厅', 640, 460),
    ])
    expect(formatResult(result)).toBe(['总面积：7.88 m²', '未计算：卧室、客厅'].join('\n'))
  })

  it('只有一边的尺寸时不硬算', () => {
    const result = calcAreas([at('3900', 120, 20), at('3600', 280, 20), at('卧室', 160, 120)])
    expect(result.status).toBe(areaStatus.noRegion)
    expect(formatResult(result)).toBe('识别到长度，但没有可计算的区域')
  })
})
